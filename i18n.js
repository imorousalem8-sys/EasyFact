window.applyLanguage = function(lang) {
  const selectedLang = (lang === 'en') ? 'en' : 'fr';
  const dict = window.i18nData[selectedLang];

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) {
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = dict[key];
      } else {
        // Retain icons if present in child elements
        const icon = el.querySelector('i');
        if (icon) {
          const iconClone = icon.cloneNode(true);
          el.innerHTML = '';
          el.appendChild(iconClone);
          el.appendChild(document.createTextNode(' ' + dict[key]));
        } else {
          el.innerText = dict[key];
        }
      }
    }
  });

  // Translate navigation items with icons dynamically
  const navMap = {
    'landing': dict.nav_home,
    'dashboard': dict.nav_dashboard,
    'invoices': dict.nav_invoices,
    'create-invoice': dict.nav_create_invoice,
    'expenses': dict.nav_expenses,
    'delivery': dict.nav_delivery,
    'clients': dict.nav_clients,
    'products': dict.nav_products,
    'export-syscohada': dict.nav_export,
    'pricing': dict.nav_pricing,
    'settings': dict.nav_settings
  };

  document.querySelectorAll('.sidebar-nav .nav-item').forEach(item => {
    const tabKey = item.getAttribute('data-tab');
    if (navMap[tabKey]) {
      const span = item.querySelector('span:not(.badge-count):not(.pulse-badge)');
      if (span) span.innerText = navMap[tabKey];
    }
  });

  // Update lang select element if present
  const langSelect = document.getElementById('lang-select');
  if (langSelect) langSelect.value = selectedLang;

  localStorage.setItem('easyfact_lang', selectedLang);
};

// Auto-apply stored language on load
document.addEventListener('DOMContentLoaded', () => {
  const savedLang = localStorage.getItem('easyfact_lang') || 'fr';
  window.applyLanguage(savedLang);
});
